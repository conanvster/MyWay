def колір_рівня(рівень):
    """Від зеленого (1) до темно-червоного (45) — щоб смуги було видно
    з одного погляду, без читання чисел."""
    t = min(1.0, max(0.0, (рівень - 1) / 44.0)) ** 0.5  # корінь: інакше
    # рівні 1…8 зливались в один зелений, а саме вони зараз і є світ
    if t < 0.5:
        k = t / 0.5
        return (int(90 + 165 * k), int(170 - 10 * k), int(70 - 40 * k))
    k = (t - 0.5) / 0.5
    return (int(255 - 95 * k), int(160 - 150 * k), int(30 - 20 * k))


def обгорнути(d, текст, шрифт, ширина):
    """Розбити рядок по словах, щоб не вилазив за легенду."""
    вийшло, рядок = [], ""
    for слово in текст.split(" "):
        проба = (рядок + " " + слово).strip()
        if d.textlength(проба, font=шрифт) > ширина and рядок:
            вийшло.append(рядок)
            рядок = слово
        else:
            рядок = проба
    if рядок:
        вийшло.append(рядок)
    return вийшло


