def смуга_зони(задум, z):
    ланка = [o for o in задум["опори"] if o["зона"] == z["номер"]]
    if not ланка:
        return None
    return (min(o["від"] for o in ланка), max(o["до"] for o in ланка))


def звіт(задум):
    """Чого бракує: смуги зон, на які в бестіарії немає жодного виду."""
    рядки = ["| Зона | Смуга рівнів | Видів на неї | Порожні п'ятірки |",
             "|---|---|---|---|"]
    for z in задум["зони"]:
        if not z["заселяти"]:
            рядки.append("| %s %s | — | — | не заселяється |"
                         % (z["номер"], z["назва"]))
            continue
        смуга = смуга_зони(задум, z)
        if смуга is None:
            рядки.append("| %s %s | ? | — | **рівні не проставлені** |"
                         % (z["номер"], z["назва"]))
            continue
        низ, верх = смуга
        свої = [v for v in задум["види"] if v["зона"] == z["номер"]]
        влучили = [v for v in свої if низ <= v["рівень"] <= верх]
        дірки, межа = [], низ
        while межа < верх:
            до = min(верх, межа + 5)
            if not any(межа <= v["рівень"] <= до for v in свої):
                дірки.append("%d–%d" % (межа, до))
            межа = до
        рядки.append("| %s %s | %d…%d | %d із %d | %s |"
                     % (z["номер"], z["назва"], низ, верх, len(влучили),
                        len(свої), ", ".join(дірки) if дірки else "немає"))
    return ("Головне тут — **яких монстрів бракує**.\n\n"
            + "\n".join(рядки)
            + "\n\nПорожні смуги — не помилка розселення, а те, що таких "
              "монстрів у бестіарії ще немає (`spec/monsters.md`).\n")


