def читати(шлях):
    with open(шлях, encoding="utf-8") as f:
        return json.load(f)


def звідки(назва, mobs, торгівля, skills):
    """Звідки річ береться — рахуємо з даних, а не з пам'яті."""
    джерела = []
    падає = []
    for номер, m in mobs.items():
        if номер == "_про":
            continue
        for drop in m.get("дроп", []):
            if drop.get("що") == назва:
                падає.append((int(m.get("рівень", 1)), m["назва"],
                              float(drop.get("шанс", 0.0))))
    if падає:
        падає.sort()
        шанси = sorted({p[2] for p in падає})
        джерела.append("падає з %d видів, рівні %d…%d, шанс %s"
                       % (len(падає), падає[0][0], падає[-1][0],
                          "…".join("%g%%" % (s * 100) for s in
                                   (шанси[:1] + шанси[-1:]
                                    if len(шанси) > 1 else шанси))))
    if назва in торгівля.get("асортимент крамаря", []):
        джерела.append("продає крамар")
    for ключ, скіл in skills.items():
        if ключ.startswith("_"):
            continue
        if скіл.get("вивчення", {}).get("руна") == назва:
            джерела.append("вчить скіл «%s»" % скіл.get("назва", ключ))
    return джерела, падає


def зібрати():
    речі = читати(ITEMS)
    mobs = читати(MOBS)
    skills = читати(SKILLS)
    торгівля = речі.get("торгівля", {})
    out = []
    for назва, дані in речі["бази"].items():
        if назва.startswith("_"):
            continue
        опис = ОПИСИ.get(назва, "")
        if not опис and назва.startswith("руна "):
            for ключ, скіл in skills.items():
                if ключ.startswith("_"):
                    continue
                if скіл.get("вивчення", {}).get("руна") == назва:
                    опис = ОПИС_РУН % скіл.get("назва", ключ)
            if not опис and "підняття" in назва:
                опис = ("Руна підняття. Піднімає вивчений скіл на "
                        "наступний рівень усередині його грейду.")
        if not опис and назва.startswith("ключ святині "):
            опис = ОПИС_КЛЮЧІВ % назва.split()[-1]
        джерела, падає = звідки(назва, mobs, торгівля, skills)
        out.append({
            "назва": назва,
            "вид": str(дані.get("вид", "")),
            "слот": str(дані.get("слот", "")),
            "грейд": str(дані.get("грейд", "")),
            "ціна": int(дані.get("ціна", 0)),
            "стати": дані.get("стати", {}),
            "дія": дані.get("дія", {}),
            "дві руки": bool(дані.get("дві руки", False)),
            "опис": опис,
            "чиї слова": "виконавець",
            "звідки": джерела,
            "падає з": [{"рівень": p[0], "вид": p[1], "шанс": p[2]}
                        for p in падає],
        })
    out.sort(key=lambda x: (ВИДИ.index(x["вид"]) if x["вид"] in ВИДИ
                            else 99, x["ціна"], x["назва"]))
    return out


def писати(каталог):
    with open(CATALOG, "w", encoding="utf-8") as f:
        json.dump(каталог, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("[речі] каталог → %s (%d речей)" % (CATALOG, len(каталог)))


