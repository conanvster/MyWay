def _точка_на_мурі(центр, кути, a):
    """Де промінь із центру під кутом `a` перетинає мур: (x, z, ребро)."""
    cx, cz = центр
    dx, dz = math.cos(a), math.sin(a)
    for k in range(len(кути)):
        (x1, z1), (x2, z2) = кути[k], кути[(k + 1) % len(кути)]
        ex, ez = x2 - x1, z2 - z1
        den = dx * ez - dz * ex
        if abs(den) < 1e-9:
            continue
        t = ((x1 - cx) * ez - (z1 - cz) * ex) / den
        u = ((x1 - cx) * dz - (z1 - cz) * dx) / den
        if t > 0 and 0 <= u <= 1:
            return cx + dx * t, cz + dz * t, k
    return None


