def документ(каталог):
    групи = {}
    for x in каталог:
        групи.setdefault(x["де"], []).append(x)
    порядок = ["у грі", "зона 1", "зона 2", "крижана північ",
               "зона 3", "зона 4",
               "підземелля 1", "підземелля 2", "підземелля 3",
               "підземелля 4"]
    рядки = ["| Де | Видів | Рівні | Моделі є |", "|---|---|---|---|"]
    for де in порядок:
        свої = групи.get(де, [])
        if not свої:
            continue
        рівні = [x["рівень"] for x in свої]
        є = len([x for x in свої if x["модель"]])
        рядки.append("| %s | %d | %d…%d | %d |"
                     % (де, len(свої), min(рівні), max(рівні), є))
    рядки.append("| **разом** | **%d** |  | **%d** |"
                 % (len(каталог), len([x for x in каталог if x["модель"]])))
    підсумок = "\n".join(рядки)

    розділи = []
    for де in порядок:
        свої = групи.get(де, [])
        if not свої:
            continue
        розділи.append("## %s" % де.capitalize())
        розділи.append("")
        розділи.append("| Рів. | Монстр | Конв. | Модель | Чиї слова | "
                       "Опис | Риси |")
        розділи.append("|---|---|---|---|---|---|---|")
        for x in sorted(свої, key=lambda v: (v["рівень"], v["назва"])):
            розділи.append("| %d | %s | %s | %s | %s | %s | %s |" % (
                x["рівень"], x["назва"], x["конвеєр"] or "—",
                "✔" if x["модель"] else "—", x["чиї слова"],
                x["опис"] or "—",
                ", ".join(x["вигляд"]["риси"]) or "—"))
        розділи.append("")
    with open(DOC, "w", encoding="utf-8") as f:
        f.write(ШАПКА.format(підсумок=підсумок,
                             розділи="\n".join(розділи)))
    print("[бестіарій] опис → %s" % DOC)


