"""Матеріали коваля — у речі й у дроп монстрів.

Слово замовника 21.09.2026: «зроби коваля, щоб він надавав послуги.
згенеруй необхідні матеріали, пропиши в монстрах, у коваля зачарування
та ремонт».

Зачарування просить метал грейду речі й рунну есенцію того ж грейду
(`game/data/smith.json`). Три метали вже були (кора дуба, залізо,
кістяний уламок), чотирьох бракувало: сталь, обсидіан, сирий кристал,
зоряний метал — вони додаються як ресурси й роздаються монстрам своєї
смуги. Есенція сюди в таблиці дропу не йде: її дає бій кожному босові
понад звичайний дроп (`combat.gd`), бо бос підземелля — це не вид, а
роль, яку отримує найсильніший вид наступної смуги.

    python3 tools/koval.py

Повторний запуск нічого не подвоює: свої рядки дропу він позначає
`"звідки": "коваль"` і перед роздачею прибирає.
"""
import collections
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ITEMS = os.path.join(ROOT, "game", "data", "items.json")
MOBS = os.path.join(ROOT, "game", "data", "mobs.json")
SMITH = os.path.join(ROOT, "game", "data", "smith.json")
МІТКА = "коваль"

# Нові метали: назва → ціна. Ціна росте втричі за грейд, як у речей.
НОВІ_МЕТАЛИ = {"сталь": 60, "мітрил": 180, "обсидіан": 540,
               "сирий кристал": 1620,
               "зоряний метал": 4860}
ЕСЕНЦІЯ_E = 200
ЦІНА_ЗА_ГРЕЙД = 3.0
ДЖЕРЕЛ = 3
ШАНС = 0.2
# Заєць (вид 2) не чіпається: `--полігон` для check.sh залежить від
# кількості його рядків дропу (попередження в `mobs.json → _про`).
НЕ_ЧІПАТИ = {"2"}


def читати(шлях):
    return json.loads(open(шлях, encoding="utf-8").read(),
                      object_pairs_hook=collections.OrderedDict)


def писати(шлях, дані):
    with open(шлях, "w", encoding="utf-8") as f:
        json.dump(дані, f, ensure_ascii=False, indent=2)
        f.write("\n")


def смуги(сходи):
    out, низ = {}, 1
    for г, до in сходи.items():
        if г.startswith("_"):
            continue
        out[г] = (низ, int(до))
        низ = int(до) + 1
    return out


def головне():
    речі = читати(ITEMS)
    мобі = читати(MOBS)
    коваль = читати(SMITH)
    сходи = речі["грейди"]["до рівня"]
    межі = смуги(сходи)
    грейди = list(межі.keys())
    бази = речі["бази"]

    нових = 0
    for назва, ціна in НОВІ_МЕТАЛИ.items():
        if назва not in бази:
            нових += 1
        бази[назва] = collections.OrderedDict(
            [("вид", "ресурс"), ("ціна", ціна), ("звідки", МІТКА)])
    for номер, г in enumerate(грейди):
        назва = "рунна есенція %s" % г
        if назва not in бази:
            нових += 1
        бази[назва] = collections.OrderedDict([
            ("вид", "ресурс"), ("грейд", г),
            ("ціна", int(round(ЕСЕНЦІЯ_E * ЦІНА_ЗА_ГРЕЙД ** номер))),
            ("_про", "Для зачарування в коваля. Падає лише з босів."),
            ("звідки", МІТКА)])
    писати(ITEMS, речі)

    # Дроп металів: спершу прибрати свої старі рядки.
    види = [(к, м) for к, м in мобі.items()
            if not к.startswith("_") and к not in НЕ_ЧІПАТИ]
    for _, м in види:
        м["дроп"] = [д for д in м.get("дроп", []) if д.get("звідки") != МІТКА]
    роздано, без_джерела = 0, []
    for г, метал in коваль["зачарування"]["матеріал"].items():
        низ, верх = межі[г]
        свої = sorted([(к, м) for к, м in види
                       if низ <= int(м.get("рівень", 1)) <= верх],
                      key=lambda x: int(x[1].get("рівень", 1)))
        є = [к for к, м in свої
             if any(д.get("що") == метал for д in м.get("дроп", []))]
        if є:
            continue  # метал уже падає у своїй смузі — не дублюємо
        if not свої:
            без_джерела.append(метал)
            continue
        крок = max(1, len(свої) // ДЖЕРЕЛ)
        for _, м in свої[::крок][:ДЖЕРЕЛ]:
            м["дроп"].append(collections.OrderedDict([
                ("що", метал), ("шанс", ШАНС), ("від", 1), ("до", 2),
                ("звідки", МІТКА)]))
            роздано += 1
    писати(MOBS, мобі)
    print("[коваль] нових ресурсів %d; рядків дропу металів %d" % (нових, роздано))
    for г, метал in коваль["зачарування"]["матеріал"].items():
        низ, верх = межі[г]
        дж = [м["назва"] for к, м in мобі.items() if not к.startswith("_")
              and низ <= int(м.get("рівень", 1)) <= верх
              and any(д.get("що") == метал for д in м.get("дроп", []))]
        print("  %-3s %-16s падає з %d видів своєї смуги" % (г, метал, len(дж)))
        if not дж:
            без_джерела.append(метал)
    if без_джерела:
        print("  ‼ без джерела: %s" % sorted(set(без_джерела)))
    return 1 if без_джерела else 0


if __name__ == "__main__":
    raise SystemExit(головне())
