#!/bin/bash
# Референси 4 зон важкого сету з еталона (П-288, 21.11.2026): одна інструкція на зону для
# всіх рас і статей, друга картинка — еталон. Готові референси пропускаються.
#   tools/zony_etalon.sh <тека-сету> <еталон.png> [зона …]
#   tools/zony_etalon.sh art/сет-еталон-людина-2026-11-21 art/еталон-важка-2026-11-20/штани-людина-s9704.png
cd "$(dirname "$0")/.."
D=$1; E=$2; shift 2
P=~/Програми/cv-venv/bin/python
n=0
for z in чоботи наручі наплічники пояс; do
  n=$((n+1))
  [ $# -gt 0 ] && [[ ! " $* " == *" $z "* ]] && continue
  $P -u tools/comfyui/ork_znulia_ref.py еталон-$z $D/зони/$z/вхід.png $D/зони/$z/реф \
      98${n}1 98${n}2 98${n}3 98${n}4 --друга $E
done
echo "ЗОНИ ГОТОВІ"
