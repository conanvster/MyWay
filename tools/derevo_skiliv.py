# -*- coding: utf-8 -*-
"""Дерево вмінь у картинках: `game/data/skills.json` → `art/скіли/*.png`.

Слово замовника 20.09.2026: «згенеруй зображення із деревами скілів».

Малюється не вигадка, а ті самі дані, з яких сервер збирає вікно
гільдмайстра: вкладка, місце [колонка, ряд], передумова, грейд, з якого
рівня, руна вивчення. Тому аркуш — це те, що гравець справді побачить:
три спільні вкладки плюс ОДНА спадкова гілка його раси, і в ній той із
двох скілів, що належить його статі.

    python3 tools/derevo_skiliv.py            # 6 аркушів + зведений
    python3 tools/derevo_skiliv.py --один людина чоловік
"""
import argparse
import json
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SKILLS = os.path.join(ROOT, "game", "data", "skills.json")
OUT = os.path.join(ROOT, "art", "скіли")
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
FONT_B = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

СПІЛЬНІ = ["Бойові навички", "Бойові кличі", "Бойові стійки"]
СПАДОК = {"людина": "Спадок людей", "ельф": "Спадок ельфів",
          "орк": "Спадок орків"}
РАСИ = ["людина", "ельф", "орк"]
СТАТІ = ["чоловік", "жінка"]

ТЛО = (26, 28, 34)
ПАНЕЛЬ = (38, 42, 52)
РАМКА = (62, 68, 82)
ТЕКСТ = (232, 230, 224)
ТЬМЯНО = (150, 155, 168)
ЛІНІЯ = (96, 104, 124)

ГРЕЙД = {"E": (58, 96, 74), "D": (52, 84, 124), "C": (96, 70, 124),
         "B": (124, 92, 48), "A": (128, 60, 60), "S": (108, 48, 108),
         "SS": (140, 112, 40)}
АКЦЕНТ = {"людина": (206, 172, 106), "ельф": (124, 192, 152),
          "орк": (198, 114, 92)}
ЗНАК = {"чоловік": "♂", "жінка": "♀"}

ШИР, ВИС = 286, 84          # вузол
ЗАЗОР_X, ЗАЗОР_Y = 46, 40   # між вузлами
ПОЛЕ = 22                   # поле всередині панелі
ЗАГОЛОВОК = 44              # смуга назви вкладки


def скіли():
    d = json.load(open(SKILLS, encoding="utf-8"))
    return {k: v for k, v in d.items() if not k.startswith("_")}


def підходить(s, раса, стать):
    """Той самий фільтр, що й на сервері (`Skill.fits`)."""
    раси = s.get("раси") or []
    статі = s.get("статі") or []
    if раси and раса not in раси:
        return False
    if статі and стать not in статі:
        return False
    return True


def вкладки(усі, раса, стать):
    """Вкладка → {ключ: скіл}, лише те, що видно цьому персонажеві."""
    out = {}
    for ключ, s in усі.items():
        вкл = s.get("вкладка", "")
        if not вкл or s.get("джерело", "дерево") != "дерево":
            continue
        if раса and not підходить(s, раса, стать):
            continue
        out.setdefault(вкл, {})[ключ] = s
    return out


def глибина(ключ, вузли, шлях=()):
    перед = вузли[ключ].get("передумова", "")
    if not перед or перед not in вузли or ключ in шлях:
        return 0
    return 1 + глибина(перед, вузли, шлях + (ключ,))


def розкласти(вузли):
    """Колонка з «місця», ряд — щоб передумова стояла ВИЩЕ за скіл."""
    out = {}
    for ключ, s in вузли.items():
        кол, ряд = s["місце"]
        out[ключ] = (кол, max(ряд, глибина(ключ, вузли)))
    зайнято = {}
    for ключ in sorted(out, key=lambda k: (out[k][1], out[k][0], k)):
        кол, ряд = out[ключ]
        while (кол, ряд) in зайнято:
            кол += 1
        зайнято[(кол, ряд)] = ключ
        out[ключ] = (кол, ряд)
    return out


def сітка(вузли):
    xy = розкласти(вузли).values()
    кол = max((c for c, _ in xy), default=0) + 1
    ряд = max((r for _, r in xy), default=0) + 1
    return кол, ряд


def розмір_панелі(вузли):
    кол, ряд = сітка(вузли)
    w = ПОЛЕ * 2 + кол * ШИР + (кол - 1) * ЗАЗОР_X
    h = ПОЛЕ * 2 + ЗАГОЛОВОК + ряд * ВИС + (ряд - 1) * ЗАЗОР_Y
    return w, h


def рамка(d, xy, fill, край, r=12, товщ=2):
    d.rounded_rectangle(xy, radius=r, fill=fill, outline=край, width=товщ)


def вузол(d, x, y, s, шрифти, акцент=None):
    ф, фм, фб = шрифти
    g = s.get("грейд", "E")
    рамка(d, (x, y, x + ШИР, y + ВИС), ГРЕЙД.get(g, (60, 60, 70)),
          акцент or РАМКА, r=10, товщ=3 if акцент else 2)
    рядки = вмістити(d, s.get("назва", "?"), фб, ШИР - 62)
    ty = y + 10 if len(рядки) > 1 else y + 18
    for рядок in рядки:
        d.text((x + 14, ty), рядок, font=фб, fill=ТЕКСТ)
        ty += 23
    d.text((x + 14, y + ВИС - 26), "з рівня %d"
           % int(s.get("з рівня", 1)), font=ф, fill=(226, 224, 216))
    руна = (s.get("вивчення") or {}).get("руна", "")
    d.text((x + 100, y + ВИС - 26), "руна" if руна else "задарма",
           font=ф, fill=(210, 208, 200) if руна else (170, 200, 170))
    # Значок грейду у правому куті.
    bw = d.textlength(g, font=фм)
    d.rounded_rectangle((x + ШИР - bw - 22, y + 10, x + ШИР - 8, y + 32),
                        radius=6, fill=(18, 19, 24))
    d.text((x + ШИР - bw - 15, y + 12), g, font=фм, fill=ТЕКСТ)
    if s.get("статі"):
        ст = s["статі"][0]
        d.text((x + ШИР - 28, y + ВИС - 28), ЗНАК.get(ст, "?"), font=фм,
               fill=акцент or ТЕКСТ)


def вмістити(d, текст, шрифт, ширина, рядків=2):
    """Розбити назву по словах; що не влізло — з трикрапкою."""
    слова = текст.split(" ")
    рядки, поточний = [], ""
    for слово in слова:
        проба = (поточний + " " + слово).strip()
        if поточний and d.textlength(проба, font=шрифт) > ширина:
            рядки.append(поточний)
            поточний = слово
        else:
            поточний = проба
    рядки.append(поточний)
    if len(рядки) > рядків:
        рядки = рядки[:рядків]
        while d.textlength(рядки[-1] + "…", font=шрифт) > ширина:
            рядки[-1] = рядки[-1][:-1]
        рядки[-1] += "…"
    return рядки


def стрілка(d, a, b, колір):
    """Від низу передумови до верху скіла, коліном якщо колонки різні."""
    ax, ay = a
    bx, by = b
    серед = (ay + by) // 2
    d.line([(ax, ay), (ax, серед), (bx, серед), (bx, by - 9)],
           fill=колір, width=3, joint="curve")
    d.polygon([(bx - 7, by - 9), (bx + 7, by - 9), (bx, by)], fill=колір)


def панель(d, x, y, назва, вузли, шрифти, акцент=None):
    ф, фм, фб = шрифти
    w, h = розмір_панелі(вузли)
    рамка(d, (x, y, x + w, y + h), ПАНЕЛЬ, акцент or РАМКА, r=16,
          товщ=3 if акцент else 2)
    d.text((x + ПОЛЕ, y + 13), назва, font=фм, fill=акцент or ТЕКСТ)
    d.line([(x + ПОЛЕ, y + ЗАГОЛОВОК - 6), (x + w - ПОЛЕ,
            y + ЗАГОЛОВОК - 6)], fill=РАМКА, width=2)

    місце = {}
    for ключ, (кол, ряд) in розкласти(вузли).items():
        місце[ключ] = (x + ПОЛЕ + кол * (ШИР + ЗАЗОР_X),
                       y + ПОЛЕ + ЗАГОЛОВОК + ряд * (ВИС + ЗАЗОР_Y))
    # Спершу стрілки, щоб вони йшли ПІД вузлами.
    сиріт = []
    for ключ, s in вузли.items():
        перед = s.get("передумова", "")
        if not перед:
            continue
        if перед not in місце:
            сиріт.append((s.get("назва", ключ), перед))
            continue
        px, py = місце[перед]
        cx, cy = місце[ключ]
        стрілка(d, (px + ШИР // 2, py + ВИС), (cx + ШИР // 2, cy), ЛІНІЯ)
    for ключ, s in вузли.items():
        mx, my = місце[ключ]
        вузол(d, mx, my, s, шрифти,
              акцент if s.get("статі") else None)
    return (w, h), сиріт


def легенда(d, x, y, w, шрифти, рядки):
    ф, фм, фб = шрифти
    хвіст = вмістити(d, рядки, ф, w - ПОЛЕ * 2, рядків=3)
    h = 78 + 22 * len(хвіст)
    рамка(d, (x, y, x + w, y + h), ПАНЕЛЬ, РАМКА, r=16)
    d.text((x + ПОЛЕ, y + 12), "Як читати", font=фм, fill=ТЕКСТ)
    cx = x + ПОЛЕ
    for g in ["E", "D", "C"]:
        рамка(d, (cx, y + 42, cx + 30, y + 64), ГРЕЙД[g], РАМКА, r=6)
        d.text((cx + 36, y + 45), "грейд %s" % g, font=ф, fill=ТЬМЯНО)
        cx += 128
    d.line([(cx + 10, y + 42), (cx + 10, y + 64)], fill=ЛІНІЯ, width=3)
    d.polygon([(cx + 3, y + 58), (cx + 17, y + 58), (cx + 10, y + 66)],
              fill=ЛІНІЯ)
    d.text((cx + 28, y + 45), "стрілка: спершу вивчити те, звідки вона",
           font=ф, fill=ТЬМЯНО)
    ty = y + 76
    for рядок in хвіст:
        d.text((x + ПОЛЕ, ty), рядок, font=ф, fill=ТЬМЯНО)
        ty += 22
    return h


def зведений(усі):
    """Один аркуш на всі три раси: спільне зверху, спадки в ряд."""
    шрифти = (ImageFont.truetype(FONT, 15),
              ImageFont.truetype(FONT_B, 17),
              ImageFont.truetype(FONT_B, 19))
    ф, фм, фб = шрифти
    видно = вкладки(усі, None, None)
    відступ = 30
    верх = 118
    верхній = [(t, розмір_панелі(видно[t])) for t in СПІЛЬНІ]
    нижній = [(СПАДОК[р], розмір_панелі(видно[СПАДОК[р]]), р) for р in РАСИ]
    W = max(sum(w for _, (w, _) in верхній) + відступ * (len(верхній) + 1),
            sum(w for _, (w, _), _ in нижній) + відступ * (len(нижній) + 1))
    H = (верх + max(h for _, (_, h) in верхній) + відступ
         + max(h for _, (_, h), _ in нижній) + відступ + 122 + відступ)
    im = Image.new("RGB", (W, H), ТЛО)
    d = ImageDraw.Draw(im)
    for i, р in enumerate(РАСИ):
        d.rectangle((W * i // 3, 0, W * (i + 1) // 3, 6), fill=АКЦЕНТ[р])
    d.text((відступ, 26), "Дерево вмінь · усі раси й статі",
           font=ImageFont.truetype(FONT_B, 30), fill=ТЕКСТ)
    скільки = sum(len(v) for v in видно.values())
    d.text((відступ, 72), "%d умінь: 16 спільних і по 6 спадкових на расу "
           "· жоден гравець не бачить усього аркуша одразу" % скільки,
           font=ф, fill=ТЬМЯНО)
    x = відступ
    for t, (w, h) in верхній:
        панель(d, x, верх, t, видно[t], шрифти)
        x += w + відступ
    y = верх + max(h for _, (_, h) in верхній) + відступ
    x = відступ
    for t, (w, h), р in нижній:
        панель(d, x, y, t, видно[t], шрифти, АКЦЕНТ[р])
        x += w + відступ
    низ = y + max(h for _, (_, h), _ in нижній) + відступ
    легенда(d, відступ, низ, W - відступ * 2, шрифти,
            "«♂/♀» — уміння, яке дістається лише цій статі: у кожній расі "
            "їх рівно два, і гільдмайстер показує гравцеві тільки своє · "
            "вміння від речей і від амулетів у дерево не потрапляють "
            "(форк П-221)")
    return im, скільки


def аркуш(усі, раса, стать):
    шрифти = (ImageFont.truetype(FONT, 15),
              ImageFont.truetype(FONT_B, 17),
              ImageFont.truetype(FONT_B, 19))
    ф, фм, фб = шрифти
    акцент = АКЦЕНТ.get(раса, (180, 180, 190))
    видно = вкладки(усі, раса, стать)
    порядок = СПІЛЬНІ + [СПАДОК[раса]]
    розміри = {t: розмір_панелі(видно[t]) for t in порядок if t in видно}

    # Дві колонки панелей; висота колонки — сума її панелей.
    ліво = [t for i, t in enumerate(порядок) if i % 2 == 0]
    право = [t for i, t in enumerate(порядок) if i % 2 == 1]
    відступ = 30
    шир_л = max(розміри[t][0] for t in ліво)
    шир_п = max(розміри[t][0] for t in право)
    W = відступ * 3 + шир_л + шир_п
    верх = 118
    вис_л = sum(розміри[t][1] for t in ліво) + відступ * (len(ліво) - 1)
    вис_п = sum(розміри[t][1] for t in право) + відступ * (len(право) - 1)
    H = верх + max(вис_л, вис_п) + відступ + 122 + відступ

    im = Image.new("RGB", (W, H), ТЛО)
    d = ImageDraw.Draw(im)
    d.rectangle((0, 0, W, 6), fill=акцент)
    d.text((відступ, 26), "Дерево вмінь · %s %s %s"
           % (раса, ЗНАК[стать], стать), font=ImageFont.truetype(FONT_B, 30),
           fill=ТЕКСТ)
    скільки = sum(len(v) for v in видно.values())
    d.text((відступ, 72), "%d умінь у чотирьох вкладках · чужої спадкової "
           "гілки сервер не показує взагалі" % скільки, font=ф, fill=ТЬМЯНО)

    сиріт = []
    y = верх
    for t in ліво:
        (w, h), с = панель(d, відступ, y, t, видно[t], шрифти,
                           акцент if t.startswith("Спадок") else None)
        сиріт += с
        y += h + відступ
    y2 = верх
    x2 = відступ * 2 + шир_л
    for t in право:
        (w, h), с = панель(d, x2, y2, t, видно[t], шрифти,
                           акцент if t.startswith("Спадок") else None)
        сиріт += с
        y2 += h + відступ
    низ = max(y, y2)
    руни = sum(1 for v in видно.values() for s in v.values()
               if (s.get("вивчення") or {}).get("руна"))
    легенда(d, відступ, низ, W - відступ * 2, шрифти,
            "%d із %d умінь вимагають руни вивчення · «♂/♀» — уміння, "
            "яке дістається лише цій статі · вміння від речей і від "
            "амулетів у дерево не потрапляють (форк П-221)"
            % (руни, скільки))
    return im, скільки, сиріт


def головна():
    p = argparse.ArgumentParser()
    p.add_argument("--один", nargs=2, metavar=("РАСА", "СТАТЬ"))
    p.add_argument("--без-зводу", action="store_true")
    a = p.parse_args()
    усі = скіли()
    os.makedirs(OUT, exist_ok=True)
    пари = [tuple(a.один)] if a.один else [(р, с) for р in РАСИ
                                           for с in СТАТІ]
    вад = 0
    for раса, стать in пари:
        im, скільки, сиріт = аркуш(усі, раса, стать)
        шлях = os.path.join(OUT, "дерево-%s-%s.png" % (раса, стать))
        im.save(шлях)
        print("  %-8s %-8s %2d умінь · %d×%d px · %s"
              % (раса, стать, скільки, im.width, im.height,
                 os.path.relpath(шлях, ROOT)))
        for назва, перед in сиріт:
            вад += 1
            print("    ‼ «%s»: передумови «%s» на аркуші немає"
                  % (назва, перед))
    if not a.один and not a.без_зводу:
        im, скільки = зведений(усі)
        шлях = os.path.join(OUT, "дерево-усі.png")
        im.save(шлях)
        print("  %-17s %2d умінь · %d×%d px · %s"
              % ("усі раси", скільки, im.width, im.height,
                 os.path.relpath(шлях, ROOT)))
    if вад:
        sys.exit("‼ вад: %d" % вад)


if __name__ == "__main__":
    головна()
