# -*- coding: utf-8 -*-
"""Скільки спорядження мусить бути, на яких рівнях і чи його дістати.

Слово замовника 20.09.2026: «визнач яка кількість предметів є
обовязковою на яких рівнях і наскільки доступні; впиши як задачі
проробити це».

Рахує з даних гри, а не з голови: комірки тіла бере з `ItemBook`,
драбину грейдів — з `items.json`, джерела — з `mobs.json` і асортименту
крамаря. Пише `spec/спорядження.md`.

    python3 tools/sporiadzhennia.py
"""
import collections
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ДАНІ = os.path.join(ROOT, "game", "data")
ITEMS = os.path.join(ДАНІ, "items.json")
MOBS = os.path.join(ДАНІ, "mobs.json")
ITEM_BOOK = os.path.join(ROOT, "game", "scripts", "item_book.gd")
ВИХІД = os.path.join(ROOT, "spec", "спорядження.md")

ВЕРХ_СВІТУ = 80         # найвищий рівень монстра в грі


def комірки():
    """Комірки тіла беремо з коду, а не переписуємо сюди: перепишеш —
    розійдеться з грою тихо."""
    текст = open(ITEM_BOOK, encoding="utf-8").read()
    рядок = re.search(r"BODY_SLOTS: Array\[String\] = \[(.+?)\]", текст,
                      re.S).group(1)
    return [x.strip().strip('"') for x in рядок.split(",") if x.strip()]


def смуги(сходи):
    низ, out = 1, []
    for грейд, верх in сходи.items():
        out.append((грейд, низ, min(int(верх), ВЕРХ_СВІТУ)))
        низ = int(верх) + 1
    return out


def зібрати():
    речі = json.load(open(ITEMS, encoding="utf-8"))
    мобі = json.load(open(MOBS, encoding="utf-8"))
    бази = речі["бази"]
    сходи = речі["грейди"]["до рівня"]
    носиме = {к: в for к, в in бази.items() if в.get("слот")}
    крамниця = set(речі.get("торгівля", {}).get("асортимент крамаря", []))

    падає = collections.defaultdict(list)
    види = 0
    у_смузі = collections.Counter()
    ряд = смуги(сходи)
    for к, м in мобі.items():
        if к.startswith("_"):
            continue
        види += 1
        L = int(м.get("рівень", 1))
        for грейд, а, б in ряд:
            if а <= L <= б:
                у_смузі[грейд] += 1
                break
        for д in м.get("дроп", []):
            падає[str(д.get("що", ""))].append(
                (str(м.get("назва", "")), L, float(д.get("шанс", 0.0))))
    # Скільки монет лишає монстр першої смуги — щоб «доступність»
    # міряти не лише вбивствами, а й грошима.
    гроші = []
    for к, м in мобі.items():
        if к.startswith("_"):
            continue
        if int(м.get("рівень", 1)) > int(сходи["E"]):
            continue
        for д in м.get("дроп", []):
            if str(д.get("що", "")) == "гроші":
                гроші.append(float(д.get("шанс", 0.0))
                             * (int(д.get("від", 0))
                                + int(д.get("до", 0))) / 2.0)
    значки = set()
    тека = os.path.join(ROOT, "game", "assets", "icons", "items")
    if os.path.isdir(тека):
        значки = {os.path.splitext(ф)[0] for ф in os.listdir(тека)}
    return dict(бази=бази, носиме=носиме, сходи=сходи, смуги=ряд,
                афікси=речі.get("афікси", {}), значки=значки,
                гроші_E=round(sum(гроші) / max(1, len(гроші))),
                крамниця=крамниця, падає=падає, види=види,
                у_смузі=у_смузі,
                слоти=комірки(), треба_в=треба_в(сходи),
                покрито_в=покрито_в(носиме, сходи))


def покрито_в(носиме, сходи):
    """Скільки обов'язкових МІСЦЬ грейду чимось закрито. Місць стільки ж,
    скільки комірок, лише персні — одне місце (одна база на два пальці),
    а зброя — два: одноручна (зі щитом) і дворучна. Після типів
    (21.09.2026) на місце буває по три-шість речей, тож лічити речі, а
    не місця, означало б «бракує мінус одинадцять»."""
    out = {}
    for г in сходи:
        свої = [в for в in носиме.values() if в.get("грейд") == г]
        місця = {в.get("слот") for в in свої if в.get("слот") != "зброя"}
        одноручна = any(в.get("слот") == "зброя" and not в.get("дві руки")
                        for в in свої)
        дворучна = any(в.get("слот") == "зброя" and в.get("дві руки")
                       for в in свої)
        out[г] = len(місця) + int(одноручна) + int(дворучна)
    return out


def треба_в(сходи):
    """Скільки баз обов'язкові на кожен грейд. Ремінь лише до
    `РЕМЕНІ_ДО`: вище його немає зовсім, тож і бракувати його не може."""
    порядок = list(сходи.keys())
    повний = len(комірки())
    return {г: повний - (1 if порядок.index(г) > порядок.index(РЕМЕНІ_ДО)
                         else 0) for г in порядок}


def очікувані_вбивства(шанси):
    """Скільки монстрів треба забити, щоб річ випала хоч раз. Беремо
    найкраще джерело: гравець піде саме до нього."""
    if not шанси:
        return None
    return round(1.0 / max(шанси))


