def матеріал_для(тип):
    if тип == "легка":
        return ЛЕГКА
    if тип == "магічна":
        return МАГІЧНА
    if тип in ("лук", "посох"):
        return ДЕРЕВО
    return МАТЕРІАЛ


def назва_речі(грейд, іменник, рід, тип="важка", слот=""):
    if грейд == "E":
        if (слот, тип) in ІМЕНА_E:
            return ІМЕНА_E[(слот, тип)]
        return "%s %s" % (іменник, З_ЧОГО_E.get(тип, "з кори дуба"))
    ч, ж, мн = матеріал_для(тип)[грейд]
    прикметник = {"ч": ч, "ж": ж, "мн": мн, "с": ж}[рід]
    return "%s %s" % (прикметник, іменник)


def драбина_баз(сходи):
    """Усі бази за типами на всі сім грейдів (E — теж, окрім прикрас і
    пояса учня, що лежать руками)."""
    порядок = list(сходи.keys())
    out = collections.OrderedDict()
    for номер, грейд in enumerate(порядок):
        if грейд != "E" and грейд not in МАТЕРІАЛ:
            continue
        for слот, тип, іменник, рід, стати, ціна, дві in НАБІР:
            if слот == "ремінь" and номер > порядок.index(РЕМЕНІ_ДО):
                continue
            if грейд == "E" and слот in РУКАМИ_E:
                continue
            назва = назва_речі(грейд, іменник, рід, тип, слот)
            запис = collections.OrderedDict([
                ("вид", "зброя" if слот == "зброя" else
                 ("амулет" if слот in ("підвіска", "перстень")
                  else "обладунок")),
                ("слот", слот),
                ("тип", тип),
            ])
            if дві:
                запис["дві руки"] = True
            if слот in ("голова", "тіло", "рукавиці", "взуття", "ремінь"):
                барва = (БАРВА_ЛЕГКА if тип == "легка" else БАРВА_МАГІЧНА
                         if тип == "магічна" else БАРВА).get(грейд)
                if барва:
                    запис["вигляд"] = collections.OrderedDict([
                        ("колір", барва),
                        ("шорсткість", ШОРСТКІСТЬ.get(грейд, 0.7))])
            запис["грейд"] = грейд
            запис["стати"] = collections.OrderedDict(
                (с, від + крок * номер) for с, (від, крок) in стати.items())
            запис["ціна"] = int(round(ціна * ЦІНА_ЗА_ГРЕЙД ** номер))
            запис["рід"] = рід
            запис["звідки"] = МІТКА
            out[назва] = запис
    return out


def роздати_дроп(нові, сходи):
    """З кого падає кожна нова база. Верхні грейди — лише з підземель."""
    мобі = читати(MOBS)
    ряд = смуги(сходи)
    межі = {г: (а, б) for г, а, б in ряд}
    # Заєць (вид 2) не чіпається: `--полігон` для check.sh залежить від
    # кількості його рядків дропу (попередження в `mobs.json → _про`).
    # Без цього він, найнижчий у смузі E, ставав джерелом усіх речей E.
    види = [(к, м) for к, м in мобі.items()
            if not к.startswith("_") and к != "2"]
    наше = set(нові)
    прибрано = 0
    for _, м in види:
        дроп = м.get("дроп", [])
        лишилось = [d for d in дроп if d.get("що") not in наше]
        прибрано += len(дроп) - len(лишилось)
        м["дроп"] = лишилось
    додано = 0
    порожні = []
    for назва, база in нові.items():
        грейд = база["грейд"]
        низ, верх = межі[грейд]
        свої = [(к, м) for к, м in види
                if низ <= int(м.get("рівень", 1)) <= верх]
        глибокі = [x for x in свої if x[1].get("підземелля")]
        беремо = глибокі if (грейд in ГЛИБОКІ and глибокі) else свої
        if not беремо:
            порожні.append(назва)
            continue
        # Розводимо по смузі, а не звалюємо на один вид: беремо кожного
        # n-го за рівнем, щоб річ падала і внизу смуги, і вгорі.
        беремо.sort(key=lambda x: int(x[1].get("рівень", 1)))
        крок = max(1, len(беремо) // ДЖЕРЕЛ_НА_РІЧ)
        обрані = беремо[::крок][:ДЖЕРЕЛ_НА_РІЧ]
        for _, м in обрані:
            м.setdefault("дроп", []).append(collections.OrderedDict([
                ("що", назва), ("шанс", ШАНС_ДРОПУ), ("від", 1), ("до", 1)]))
            додано += 1
    # Старі речі E роздавались іще руками, і три з них падали по 3% —
    # це ~33 вбивства, гірше за межу задачі З-3. Не переписуємо їхніх
    # джерел (вони доречні), а піднімаємо найкраще з них до тієї самої
    # межі.
    піднято = 0
    старі = {к for к, в in bases_items(читати(ITEMS)["бази"])
             if в.get("слот") and в.get("звідки") != МІТКА}
    найкраще = {}
    for _, м in види:
        for д in м.get("дроп", []):
            назва = str(д.get("що", ""))
            if назва in старі:
                кращий = найкраще.get(назва)
                if кращий is None or float(д["шанс"]) > float(кращий["шанс"]):
                    найкраще[назва] = д
    for назва, д in найкраще.items():
        if float(д["шанс"]) < ШАНС_ДРОПУ:
            д["шанс"] = ШАНС_ДРОПУ
            піднято += 1
    писати(MOBS, мобі)
    if піднято:
        print("          старим речам E піднято шанс до %.0f%%: %d"
              % (ШАНС_ДРОПУ * 100, піднято))
    return прибрано, додано, порожні


def читати(шлях):
    return json.loads(open(шлях, encoding="utf-8").read(),
                      object_pairs_hook=collections.OrderedDict)


def писати(шлях, дані):
    with open(шлях, "w", encoding="utf-8") as f:
        json.dump(дані, f, ensure_ascii=False, indent=2)
        f.write("\n")


def зібрати_драбину():
    речі = читати(ITEMS)
    сходи = речі["грейди"]["до рівня"]
    нові = драбина_баз(сходи)
    бази = речі["бази"]
    було = len([1 for в in бази.values()
                if isinstance(в, dict) and в.get("звідки") == МІТКА])
    for к in [к for к, в in bases_items(бази) if в.get("звідки") == МІТКА]:
        del бази[к]
    for назва, запис in нові.items():
        # Речі E вже мають свою текстуру (кора дуба) — генератор дає лише
        # барву, тож чужий «вигляд» не затираємо.
        було_вигляд = бази.get(назва, {}).get("вигляд")
        if було_вигляд and "текстура" in було_вигляд:
            запис["вигляд"] = було_вигляд
        бази[назва] = запис

    # З-4: крамар тримає лише два нижні грейди носимого.
    порядок = list(сходи.keys())
    межа = порядок.index(ПРОДАЄМО_ДО)
    торг = речі.setdefault("торгівля", {})
    асортимент = [н for н in торг.get("асортимент крамаря", [])
                  if not бази.get(н, {}).get("слот")]
    для_продажу = [н for н, в in bases_items(бази)
                   if в.get("слот")
                   and порядок.index(в.get("грейд", "E")) <= межа]
    торг["асортимент крамаря"] = для_продажу + асортимент

    # З-6: розмах афікса росте з грейдом речі.
    афікси = речі.setdefault("афікси", {})
    афікси["_про крок"] = ("Розмах афікса множиться на "
                           "1 + «крок за грейд» × номер грейду речі: "
                           "«міцний» на SS дає більше, ніж на E.")
    афікси["крок за грейд"] = 0.6

    писати(ITEMS, речі)
    прибрано, додано, порожні = роздати_дроп(нові, сходи)
    print("[драбина] нових баз %d (було своїх %d), у крамниці носимого %d"
          % (len(нові), було, len(для_продажу)))
    print("          дроп: прибрано %d, роздано %d джерел"
          % (прибрано, додано))
    if порожні:
        print("          ‼ без джерела лишились: %s" % порожні)
    return len(порожні)


def bases_items(бази):
    return [(к, в) for к, в in бази.items() if isinstance(в, dict)]


if __name__ == "__main__":
    import sys as _sys
    if "--зібрати" in _sys.argv:
        _sys.exit(1 if зібрати_драбину() else головна())
