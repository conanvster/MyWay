class Рельєф:
    """Висота й код краю в точці — з тих самих файлів, що читає гра."""

    def __init__(self, карта):
        земля = карта["земля"]
        self.n = int(земля["точок"])
        self.крок = float(земля["сторона"]) / (self.n - 1)
        self.ox = -float(земля["початок"][0])
        self.oz = -float(земля["початок"][1])
        корінь = os.path.join(ROOT, "game")
        with open(os.path.join(корінь, земля["рельєф"][6:]), "rb") as f:
            сире = f.read()
        self.метри = struct.unpack("<%df" % (len(сире) // 4), сире)
        with open(os.path.join(корінь, земля["зони"][6:]), "rb") as f:
            self.край = f.read()

    def _клітина(self, cx, cz):
        gx = int(round((cx + self.ox) / self.крок))
        gy = int(round((cz + self.oz) / self.крок))
        if not (0 <= gx < self.n and 0 <= gy < self.n):
            return None
        return gy * self.n + gx

    def сухо(self, cx, cz, рад):
        for k in range(9):
            a = 6.2832 * k / 8.0
            r = 0.0 if k == 8 else рад
            i = self._клітина(cx + math.cos(a) * r, cz + math.sin(a) * r)
            if i is None or not self.край[i]:
                return False
            if self.метри[i] < BEREG + 1.5:
                return False
        return True

    def код(self, cx, cz):
        i = self._клітина(cx, cz)
        return 0 if i is None else self.край[i]


