def краї_пропозиція(сходинки, шанс=0.5):
    види = види_за_назвою()
    смуги = {}
    for s in сходинки:
        смуги.setdefault(s["смуга"], []).append(s["рівень"])
    out = []
    for край, лінія in ЛІНІЇ_КРАЇВ.items():
        for смуга in sorted(смуги, key=int):
            середній = sum(смуги[смуга]) / float(len(смуги[смуга]))
            назва = min(лінія, key=lambda n: abs(види[n][1] - середній))
            номер, рівень = види[назва]
            out.append(dict(край=край, смуга=смуга, вид=номер, назва=назва,
                            рівень=рівень,
                            гнізд=max(1, int(round(5 - рівень / 10.0))),
                            шанс=шанс))
    return out


