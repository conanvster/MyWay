                свої = [v for v in задум["види"] if v["зона"] == z["номер"]
                        and низ <= v["рівень"] <= верх]
                if not свої:
                    ключ = (z["номер"], int(низ / 10) * 10)
                    порожні[ключ] = порожні.get(ключ, 0) + 1
                    continue
                if зайнято(cx, cz, рад):
                    continue
