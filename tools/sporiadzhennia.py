         "рукавиці, взуття, щит, зброя одноручна, зброя дворучна, "
         "підвіска, перстень). Назви й вигляд за смугою світу: кора дуба "
         "на E, залізо на D, кістка й обсидіан на верхніх. Готово, коли "
         "в кожного слота кожного грейду є щонайменше одна база."
