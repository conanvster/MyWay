def риси_з_опису(опис, назва):
    текст = (назва + " " + опис).lower()
    out = []
    for взірець, риса in РИСИ:
        if re.search(взірець, текст) and риса not in out:
            out.append(риса)
    return out


def розмір(рівень, конвеєр, риси):
    """Грубо: росте з рівнем, «велет» додає половину, дрібнота зменшує."""
    основа = {"Ч": 0.6, "Л": 1.8, "К": 1.8, "З": 0.4, "С": 0.4,
              "Д": 0.8}[конвеєр]
    k = 1.0 + рівень / 90.0
    if "велет" in риси:
        k *= 1.6
    return round(основа * k, 2)


def запис(назва, рівень, конвеєр, опис, де, чиї):
    риси = риси_з_опису(опис, назва)
    if "крила" in риси and конвеєр in ("Ч", "Л"):
        риси.remove("крила")     # крила на чотирилапому — окрема робота
    текстура, колір = БАРВИ[де]
    return {
        "назва": назва, "рівень": рівень, "де": де, "конвеєр": конвеєр,
        "опис": опис, "чиї слова": чиї,
        "вигляд": {"розмір": розмір(рівень, конвеєр, риси),
                   "текстура": текстура,
                   "колір": [round(c, 3) for c in колір],
                   "риси": риси},
        "модель": "",
    }


def зібрати():
    """Каталог із нуля: спершу те, що вже в грі, тоді додане."""
    out = []
    mobs = json.load(open(MOBS, encoding="utf-8"))
    для_зони = {}
    try:
        сюди = json.load(open(os.path.join(ROOT, "spec",
                                           "розселення-зони.json"),
                              encoding="utf-8"))
        для_зони = сюди
    except OSError:
        pass
    for номер, m in mobs.items():
        if номер == "_про":
            continue
        вигляд = m.get("вигляд", {})
        модель = str(вигляд.get("модель", ""))
        out.append({
            "назва": m["назва"], "рівень": int(m.get("рівень", 1)),
            "де": для_зони.get(m["назва"], "у грі"),
            "конвеєр": "", "опис": "", "чиї слова": "виконавець",
            "вигляд": {"розмір": float(вигляд.get("зріст", 1.0)),
                       "текстура": "", "колір": [], "риси": []},
            "модель": модель, "вид": int(номер),
        })
    for де, чиї, перелік in ДОДАНІ:
        for назва, рівень, конвеєр, опис in перелік:
            вже = [x for x in out if x["назва"] == назва]
            if вже:
                вже[0]["де"] = де
                вже[0]["опис"] = опис
                вже[0]["чиї слова"] = чиї
                вже[0]["конвеєр"] = конвеєр
                вже[0]["вигляд"]["риси"] = риси_з_опису(опис, назва)
                continue
            out.append(запис(назва, рівень, конвеєр, опис, де, чиї))
    out.sort(key=lambda x: (x["де"], x["рівень"], x["назва"]))
    return out


def читати():
    if not os.path.exists(CATALOG):
        каталог = зібрати()
        писати(каталог)
        return каталог
    return json.load(open(CATALOG, encoding="utf-8"))


def писати(каталог):
    os.makedirs(os.path.dirname(CATALOG), exist_ok=True)
    with open(CATALOG, "w", encoding="utf-8") as f:
        json.dump(каталог, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("[бестіарій] каталог → %s (%d видів)" % (CATALOG, len(каталог)))


