class Рельєф:
    """Висота й код краю в точці — з тих самих файлів, що читає гра."""

    def __init__(self, карта):
        земля = карта["земля"]
        self.n = int(земля["точок"])
        self.крок = float(земля["сторона"]) / (self.n - 1)
        self.ox = -float(земля["початок"][0])
        self.oz = -float(земля["початок"][1])
        корінь = os.path.join(ROOT, "game")
        with open(os.path.join(корінь, земля["рельєф"][6:]), "rb") as f:
            сире = f.read()
        self.метри = struct.unpack("<%df" % (len(сире) // 4), сире)
        with open(os.path.join(корінь, земля["зони"][6:]), "rb") as f:
            self.край = f.read()

    def _клітина(self, cx, cz):
        gx = int(round((cx + self.ox) / self.крок))
        gy = int(round((cz + self.oz) / self.крок))
        if not (0 <= gx < self.n and 0 <= gy < self.n):
            return None
        return gy * self.n + gx

    def сухо(self, cx, cz, рад):
        for k in range(9):
            a = 6.2832 * k / 8.0
            r = 0.0 if k == 8 else рад
            i = self._клітина(cx + math.cos(a) * r, cz + math.sin(a) * r)
            if i is None or not self.край[i]:
                return False
            if self.метри[i] < BEREG + 1.5:
                return False
        return True

    def код(self, cx, cz):
        i = self._клітина(cx, cz)
        return 0 if i is None else self.край[i]


def перерахувати(задум):
    """Нові «зони появи» за таблицею — на справжньому рельєфі."""
    карта = читати(MAP)
    земля = Рельєф(карта)
    сторона = float(карта["земля"]["сторона"])
    краї = {z["назва"]: z["код"] for z in карта["зони"]}
    міста, села = карта["міста"], карта["села"]
    орієнтири = карта["орієнтири"]
    rw = random.Random(SID)
    рад_від, рад_до = задум["радіус"]
    зони = []

    def зайнято(cx, cz, рад):
        for m in міста + села:
            r = m.get("рівне", m["радіус"]) + рад + 12.0
            if ((cx - m["центр"][0]) ** 2 + (cz - m["центр"][2]) ** 2
                    < r * r):
                return True
        for o in орієнтири:
            r = o["радіус"] + рад + 10.0
            if (cx - o["де"][0]) ** 2 + (cz - o["де"][2]) ** 2 < r * r:
                return True
        for z in зони:
            r = z["радіус"] + рад + 40.0
            if (cx - z["де"][0]) ** 2 + (cz - z["де"][2]) ** 2 < r * r:
                return True
        return False

    за_краєм = {}
    for k in задум["край"]:
        код = краї.get(k["край"])
        if код is None:
            sys.exit("‼ у «Краї» немає такого краю: %s" % k["край"])
        за_краєм.setdefault(код, {})[str(k["смуга"])] = k

    ox, oz = -float(карта["земля"]["початок"][0]), \
        -float(карта["земля"]["початок"][1])
    # Два проходи: спершу густіша сітка біля столиці, тоді рідша по
    # всьому світу. Без першого в перші смуги (150…600 м) потрапляло
    # три-чотири зони на всю околицю, і частина початкових видів — заєць,
    # ведмідь — не діставалась нікуди.
    БІЛЯ = 600.0
    for крок, лише_близько in ((задум["крок_біля"], True),
                               (задум["крок"], False)):
        ряди = int(сторона // крок)
        for iy in range(ряди):
            for ix in range(ряди):
                cx = (ix + 0.5) * крок - ox + rw.uniform(-крок * 0.3,
                                                         крок * 0.3)
                cz = (iy + 0.5) * крок - oz + rw.uniform(-крок * 0.3,
                                                         крок * 0.3)
                рад = rw.uniform(рад_від, рад_до)
                d = math.hypot(cx, cz)
                кидок = rw.random()
                зміна = rw.choice([-1, 0, 0, 1])
                if лише_близько and d > БІЛЯ:
                    continue
                if d < задум["порожньо"] \
                        or not земля.сухо(cx, cz, рад + 6.0):
                    continue
                if зайнято(cx, cz, рад):
                    continue
                підходять = [s for s in задум["сходинки"]
                             if s["від"] <= d < s["до"]]
                if not підходять:
                    підходять = [max(задум["сходинки"],
                                     key=lambda s: s["до"])]
                взяв = підходять[int(кидок * len(підходять))
                                 % len(підходять)]
                вид, гнізд = взяв["вид"], взяв["гнізд"]
                у_краю = за_краєм.get(земля.код(cx, cz), {})
                свій = у_краю.get(str(взяв["смуга"])) or у_краю.get("усі")
                if свій and d > задум["край_від"] and кидок < свій["шанс"]:
                    вид, гнізд = свій["вид"], свій["гнізд"]
                зони.append({"де": [round(cx, 1), 0, round(cz, 1)],
                             "радіус": round(рад, 1),
                             "вид": вид, "скільки": max(1, гнізд + зміна),
                             "агресивний": вид != 2,
                             "респавн": 12.0, "розкид респавну": 4.0,
                             "далеко від міста": round(d, 0)})
    return зони


def застосувати(задум):
    зони = перерахувати(задум)
    with open(MAP, encoding="utf-8") as f:
        карта = json.load(f)
    було = len(карта["зони появи"])
    карта["зони появи"] = зони
    with open(MAP, "w", encoding="utf-8") as f:
        json.dump(карта, f, ensure_ascii=False, indent=2)
        f.write("\n")
    mobs = читати(MOBS)
    рівні = sorted({int(mobs[str(z["вид"])]["рівень"]) for z in зони})
    print("[розселення] map2.json: зон %d → %d, гнізд %d, рівні %d…%d"
          % (було, len(зони), sum(z["скільки"] for z in зони),
             рівні[0], рівні[-1]))


