def колір_рівня(рівень):
    """Від зеленого (1) до темно-червоного (ВЕРХ). Корінь — інакше низи
    зливаються в один зелений."""
    t = min(1.0, max(0.0, (рівень - 1) / float(ВЕРХ - 1))) ** 0.5
    if t < 0.5:
        k = t / 0.5
        return (int(90 + 165 * k), int(170 - 10 * k), int(70 - 40 * k))
    k = (t - 0.5) / 0.5
    return (int(255 - 95 * k), int(160 - 150 * k), int(30 - 20 * k))


