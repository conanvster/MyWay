def читати_модель():
    with open(os.path.join(ДЖЕРЕЛО, "_model.json"), encoding="utf-8") as f:
        m = json.load(f)
    n = ТОЧОК
    with open(os.path.join(ДЖЕРЕЛО, "_relief_%d.u16" % n), "rb") as f:
        raw = f.read()
    висота = [v / 65535.0 * 2.2 for v in struct.unpack("<%dH" % (n * n), raw)]
    with open(os.path.join(ДЖЕРЕЛО, "_zones_%d.u8" % n), "rb") as f:
        зона = list(f.read())
    if len(зона) != n * n:
        sys.exit("зони не того розміру: %d замість %d" % (len(зона), n * n))
    return m, висота, зона


def відстань_до_суші(зона, n, крок_px):
    """Скільки клітин до найближчої суші — для глибини дна.

    Двопрохідна шахова відстань: досить точна для схилу дна й коштує
    один прохід туди й один назад замість справжньої евклідової.
    """
    ВЕЛИКЕ = 10 ** 9
    d = [0 if зона[i] else ВЕЛИКЕ for i in range(n * n)]
    for iy in range(n):
        for ix in range(n):
            i = iy * n + ix
            if d[i] == 0:
                continue
            best = d[i]
            if ix:
                best = min(best, d[i - 1] + 1)
            if iy:
                best = min(best, d[i - n] + 1)
            if ix and iy:
                best = min(best, d[i - n - 1] + 1)
            if ix < n - 1 and iy:
                best = min(best, d[i - n + 1] + 1)
            d[i] = best
    for iy in range(n - 1, -1, -1):
        for ix in range(n - 1, -1, -1):
            i = iy * n + ix
            if d[i] == 0:
                continue
            best = d[i]
            if ix < n - 1:
                best = min(best, d[i + 1] + 1)
            if iy < n - 1:
                best = min(best, d[i + n] + 1)
            if ix < n - 1 and iy < n - 1:
                best = min(best, d[i + n + 1] + 1)
            if ix and iy < n - 1:
                best = min(best, d[i + n - 1] + 1)
            d[i] = best
    return d


def головне():
    модель, висота, зона = читати_модель()
    n = ТОЧОК
    сторона_px = модель["сторона"]
    сторона = сторона_px * МАСШТАБ
    крок = сторона / (n - 1)
    крок_px = сторона_px / (n - 1)

    # ---- початок координат: столиця стає (0,0) ----
    # На цю точку жорстко зав'язані спавн (world.gd) і оживлення
    # (combat.gd). Столицею беремо найбільше місто карти.
    міста_карти = [o for o in модель["об_єкти"] if o["вид"] == "місто"]
    столиця = max(міста_карти, key=lambda o: o["радіус"])
    ox, oz = столиця["x"] * МАСШТАБ, столиця["y"] * МАСШТАБ

    def у_гру(px, py):
        return (px * МАСШТАБ - ox, py * МАСШТАБ - oz)

    # ---- висота в метрах ----
    суша = sorted(висота[i] for i in range(n * n) if зона[i])
    низ = суша[len(суша) // 100]          # 1-й процентиль: рівень берега
    далеко = відстань_до_суші(зона, n, крок_px)
    метри = [0.0] * (n * n)
    for i in range(n * n):
        if зона[i]:
            метри[i] = БЕРЕГ + (висота[i] - низ) * ВЕРТИКАЛЬ
            if метри[i] < 0.5:
                метри[i] = 0.5      # суша не пірнає під воду сама собою
        else:
            d = далеко[i] * крок
            t = min(1.0, d / ДНО_СХИЛ)
            метри[i] = -ДНО_ГЛИБИНА * (t * t * (3.0 - 2.0 * t))

    # ---- річки: врізати русло в рельєф ----
    # На карті річки намальовані лінією, у грі ж вода мусить текти в
    # заглибині, інакше вона лежить плямою поверх схилу. Русло веде
    # ТУДИ Ж, куди й намальоване: клітини ті самі, з моделі.
    C_ = модель["клітина"]
    русла_гра = []
    for шлях in модель["русла"]:
        точки = []
        йде = None
        n_шлях = max(1, len(шлях) - 1)
        for k, (gx, gy) in enumerate(шлях):
            px, py = (gx + 0.5) * C_, (gy + 0.5) * C_
            x, z = у_гру(px, py)
            ix = min(n - 1, max(0, int(round(px / крок_px))))
            iy = min(n - 1, max(0, int(round(py / крок_px))))
            дно = метри[iy * n + ix]
            # Строго вниз: у полі рельєфу трапляються дрібні горби, і
            # без цього русло текло б угору, а вода стояла б сходинками.
            йде = дно if йде is None else min(йде, дно)
            частка = k / n_шлях
            шир = РІЧКА_ШИР_ВІД + (РІЧКА_ШИР_ДО - РІЧКА_ШИР_ВІД) * частка
            точки.append((x, z, йде, шир))
        русла_гра.append(точки)

    for точки in русла_гра:
        for x, z, дно, шир in точки:
            край = шир * РІЧКА_БЕРЕГ
            r = int(край / крок) + 1
            gx = int(round((x + ox) / крок_px))
            gy = int(round((z + oz) / крок_px))
            for dy in range(-r, r + 1):
                for dx in range(-r, r + 1):
                    jx, jy = gx + dx, gy + dy
                    if not (0 <= jx < n and 0 <= jy < n):
                        continue
                    d = math.hypot(dx, dy) * крок
                    if d > край:
                        continue
                    # Всередині русла — рівне дно, далі плавно вгору.
                    t = 0.0 if d <= шир * 0.5 else (d - шир * 0.5) / (край - шир * 0.5)
                    ціль = дно - РІЧКА_ГЛИБ * (1.0 - t * t)
                    i = jy * n + jx
                    if ціль < метри[i]:
                        метри[i] = ціль

    # ---- об'єкти ----
    rnd = random.Random(СІД)

    def висота_в(px, py):
        gx = min(n - 1, max(0, int(round(px / крок_px))))
