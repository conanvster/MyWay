def читати_таблицю():
    """Розбір `spec/розселення.md`: три таблиці з-під своїх заголовків."""
    if not os.path.exists(TABLE):
        sys.exit("‼ немає %s — спершу `--знімок`" % TABLE)
    with open(TABLE, encoding="utf-8") as f:
        рядки = f.read().splitlines()
    зараз = None
    таблиці = {}
    for рядок in рядки:
        if рядок.startswith("## "):
            зараз = рядок[3:].split("—")[0].strip()
            таблиці[зараз] = []
        elif зараз and рядок.startswith("|"):
            комірки = [c.strip() for c in рядок.strip("|").split("|")]
            if all(set(c) <= set("-: ") for c in комірки):
                continue
            таблиці[зараз].append(комірки)
    види = види_за_назвою()

    сходинки = []
    for ряд in таблиці.get("Сходинки", [])[1:]:
        смуга, від, до, вид, рівень, гнізд = ряд[:6]
        if вид not in види:
            sys.exit("‼ у «Сходинках» невідомий вид: %s" % вид)
        номер, справжній = види[вид]
        if int(рівень) != справжній:
            print("  ‼ %s: у таблиці рівень %s, у mobs.json %d — беру %d"
                  % (вид, рівень, справжній, справжній))
        сходинки.append(dict(смуга=смуга, від=float(від), до=float(до),
                             вид=номер, назва=вид, рівень=справжній,
                             гнізд=int(гнізд)))
    край = []
    for ряд in таблиці.get("Край", [])[1:]:
        назва_краю, смуга, вид, гнізд, шанс = ряд[:5]
        if вид not in види:
            sys.exit("‼ у «Краї» невідомий вид: %s" % вид)
        номер, рівень = види[вид]
        край.append(dict(край=назва_краю, смуга=смуга, вид=номер,
                         назва=вид, рівень=рівень, гнізд=int(гнізд),
                         шанс=float(шанс.replace(",", "."))))
    числа = {}
    for ряд in таблиці.get("Щільність", [])[1:]:
        числа[ряд[0]] = ряд[1]

    def число(ключ, стандарт):
        for назва, значення in числа.items():
            if назва.startswith(ключ):
                if "…" in значення:
                    a, b = значення.split("…")
                    return float(a), float(b)
                return float(значення)
        return стандарт

    return dict(сходинки=сходинки, край=край,
                крок=число("Крок сітки зон", 200.0),
                крок_біля=число("Крок сітки біля", 120.0),
                радіус=число("Радіус", (20.0, 34.0)),
                порожньо=число("Ближче", 150.0),
                край_від=число("Далі", 900.0))


def таблиця_з_гри():
    """Знімок: звести 360 зон гри назад у сходинки — щоб було видно, що
    саме зараз стоїть, і було з чого правити."""
    карта = читати(MAP)
    mobs = читати(MOBS)
    межі = [600.0, 1200.0, 1900.0, 2600.0, 1e9]
    зведення = {}
    for z in карта["зони появи"]:
        d = float(z.get("далеко від міста", 0.0))
        смуга = next(i for i, m in enumerate(межі) if d < m)
        ключ = (смуга, int(z["вид"]))
        зведення.setdefault(ключ, []).append(int(z["скільки"]))
    сходинки = []
    низ = 150.0
    for i, верх in enumerate(межі):
        для_смуги = sorted(k for k in зведення if k[0] == i)
        for _, вид in для_смуги:
            скільки = зведення[(i, вид)]
            m = mobs[str(вид)]
            сходинки.append(dict(
                смуга=str(i + 1), від=низ,
                до=(верх if верх < 1e8 else 3000.0),
                вид=вид, назва=m["назва"], рівень=int(m["рівень"]),
                гнізд=int(round(sum(скільки) / len(скільки)))))
        низ = верх if верх < 1e8 else низ
    return сходинки


def найдалі():
    """Найдальша суха точка від столиці (98-й відсоток) — далі смуги
    тягти нема куди: кут аркуша за 5 км від столиці вже море, і смуги
    8–9 виходили порожні, а найсильніші види — ніде."""
    карта = читати(MAP)
    земля = Рельєф(карта)
    сторона = float(карта["земля"]["сторона"])
    ox, oz = -float(карта["земля"]["початок"][0]), \
        -float(карта["земля"]["початок"][1])
    крок = 100.0
    відстані = []
    for iy in range(int(сторона // крок)):
        for ix in range(int(сторона // крок)):
            cx = (ix + 0.5) * крок - ox
            cz = (iy + 0.5) * крок - oz
            if земля.сухо(cx, cz, 30.0):
                відстані.append(math.hypot(cx, cz))
    відстані.sort()
    return відстані[int(len(відстані) * 0.98)]


def пропозиція(смуг=9, далеко=None):
    """Сходинки з УСІХ видів `mobs.json`: види за рівнем, смуги — що далі
    від столиці, то сильніші. Це пропозиція виконавця (П-188), не
    рішення: замовник править таблицю, а не цей код.

    Гнізд у зоні спадає з рівнем: слабких багато, сильних одиниці."""
    далеко = далеко or найдалі()
    mobs = читати(MOBS)
    види = sorted(((int(k), m["назва"], int(m["рівень"]))
                   for k, m in mobs.items() if k != "_про"),
                  key=lambda v: (v[2], v[1]))
    # Смуги розширюються з відстанню, але не геометрично: при
    # геометричних перші смуги виходили по 70 м завширшки, і майже вся
    # суша діставалась найсильнішим.
    межі = [150.0 + (далеко - 150.0) * (i / float(смуг)) ** 1.35
            for i in range(смуг + 1)]
    межі[-1] = 9000.0   # остання смуга ловить і кути за 98-м відсотком
    print("[розселення] суша тягнеться на %.0f м від столиці" % далеко)
    сходинки = []
    for i in range(смуг):
        частка = види[len(види) * i // смуг:len(види) * (i + 1) // смуг]
        for номер, назва, рівень in частка:
            сходинки.append(dict(
                смуга=str(i + 1), від=round(межі[i], -1),
                до=round(межі[i + 1], -1), вид=номер, назва=назва,
                рівень=рівень, гнізд=max(1, int(round(5 - рівень / 10.0)))))
    return сходинки


