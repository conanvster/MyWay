#!/usr/bin/env bash
# Запуск проєкту. За замовчуванням — на ДИСКРЕТНІЙ NVIDIA.
#
#   ./run.sh          редактор
#   ./run.sh --run    одразу гру (клієнт до 127.0.0.1)
#   ./run.sh --демо   гру в режимі показу: сама бере ціль, б'є і знімає екран
#   ./run.sh --демо-вікна  те саме, але ще й відкриває «Речі» й «Стати»
#   ./run.sh --демо-крамар те саме, але йде до крамаря й торгує
#   ./run.sh --парад  парад істот: усі види в ряд, знімок у user://
#   ./run.sh --рослини  показ рослин: усі дерева, кущі, трави й каміння
#                     набору природи в ряд, з підписами й зміряними висотами
#   ./run.sh --рухи-людини  парад рухів моделі людини: по одній фігурі
#                     на кожен рух із бібліотеки, кожна підписана назвою
#                     (`--модель res://…` — інша модель на тому самому
#                     скелеті, напр. аватар MPFB
#                     res://models/own/avatary/mpfb/людина-чоловік-mpfb.gltf)
#   ./run.sh --рухи-монстрів  те саме для монстрів: по фігурі на пару
#                     «вид+рух»; хто ще на фігурці з примітивів —
#                     стій→іди→бий по колу, як у --парад; тут же (без
#                     kind у мобах) — орк і 6 тварин Farm Animals Pack
#   ./run.sh --моделі  ПЕРЕГЛЯДАЧ МОДЕЛЕЙ: ліворуч усі моделі (аватари,
#                     власні монстри, гуманоїди) з пошуком, праворуч рухи
#                     кнопками й скін: як у грі / без скіна (глина) /
#                     будь-яка картинка поруч з моделлю чи в
#                     models/own/skins/<модель>/
#   ./run.sh --звірі-скан     заєць, вовк, кажан, скорпіон за референсом: по фігурі на
#                             рух, з хутром, на підставках (--знімок <основа>)
#   ./run.sh --нові-моделі  104 щойно завантажені персонажі (ще не в
#                     репозиторії, читає напряму з ~/assets/: RPG+Ultimate
#                     Character Pack, решта Ultimate Monster Pack, 4
#                     скелети KayKit): кожен сам по колу програє ввесь
#                     свій список рухів
#   ./run.sh --печери  печери-підземелля згори: форма, вихід,
#                     палата боса, і чи все зв'язано
#   ./run.sh --підземелля  десять низькорівневих підземель (П-190): 1…0 —
#                     котре, Tab — прохід очима / згори як у грі; числа
#                     зв'язності й заселення за воротами E, D, C
#   ./run.sh --святині  святині й портали (П-153): 5 форм × 3 стани,
#                     7 грейдів кольором, і аналіз — скільки святинь
#                     узагалі влазить у теперішню мапу
#   ./run.sh --вітрина  вікна «Речі», «Стати», «Скіли» з речами в кожному слоті
#   ./run.sh --run    клієнт в ОСНОВНОМУ світі — це світ 2 (П-205).
#   ./run.sh --світ1  клієнт у світі 600 м: він лишився для проб.
#                     Сервер треба підняти з тим самим: ./run-server.sh --світ1
#   ./run.sh --світ2-згори  увесь світ версії 2 згори одним знімком —
#                     щоб порівняти з намальованим аркушем карти
#   ./run.sh --світ2-карта  карта світу версії 2: цілий аркуш і
#                     збільшений вигляд плитками
#   ./run.sh --світ2-місця  світ версії 2 з землі: межа зон, гори,
#                     русло, мертвий схід, крижана північ — по знімку
#
# Сервер піднімається окремо: ./run-server.sh
#
# Чому тут узагалі є вибір карти: LM Studio тримає модель на NVIDIA і
# займає майже всю її пам'ять (04.09.2025 було 15778 з 16311 МіБ). Godot
# тоді не може створити пристрій Vulkan і падає з "VkResult error -3".
# Тож скрипт дивиться, скільки на ній вільно, і сам вирішує:
#
#   вільно ≥ 2000 МіБ  -> дискретна NVIDIA (швидша, потрібна для світу з туманом)
#   вільно менше       -> вбудована AMD, із попередженням
#   AMD=1 ./run.sh  -> силувано вбудована
#
# Перевірити, куди воно справді пішло, можна за першим рядком журналу:
# Godot друкує "Using Device #N: ...".

set -euo pipefail
proj="$(cd "$(dirname "$0")" && pwd)/game"
amd_icd=/usr/share/vulkan/icd.d/radeon_icd.json

# NOVSYNC=1 — не чекати вертикальної синхронізації.
#
# Навіщо (заміряно 05.09.2026). Композитор не показує кадри вікну, якого
# не видно — інше вікно зверху, інший стіл, замкнений екран. Godot при
# цьому впирається у показ кадру й іде 1 кадр за секунду: GPU 0%, ЦП 19%,
# тобто не завантажений, а саме заблокований. Той самий клієнт із
# `--disable-vsync` дає 300–450 кадрів за секунду.
#
# Для гри це не потрібно (людина дивиться на вікно), а для перевірок —
# так: інакше `check.sh` міряє стан робочого столу, а не гру.
vsync=()
if [ "${NOVSYNC:-0}" = "1" ]; then
    vsync=(--disable-vsync)
fi

if [ "${AMD:-0}" = "1" ]; then
    export VK_ICD_FILENAMES="$amd_icd"
    echo "→ вбудована AMD (силувано)"
else
    free=$(nvidia-smi --query-gpu=memory.free --format=csv,noheader,nounits 2>/dev/null || echo 0)
    if [ "$free" -ge 2000 ]; then
        echo "→ дискретна NVIDIA, вільно ${free} МіБ"
    else
        echo "‼ на NVIDIA вільно лише ${free} МіБ — беру вбудовану AMD." >&2
        echo "  щоб звільнити:  lms unload --all" >&2
        export VK_ICD_FILENAMES="$amd_icd"
    fi
fi

case "${1:-}" in
    --run)  exec godot --path "$proj" "${vsync[@]}" -- "${@:2}" ;;
    --світ1) exec godot --path "$proj" "${vsync[@]}" -- --світ1 "${@:2}" ;;
    --світ2) exec godot --path "$proj" "${vsync[@]}" -- --світ2 "${@:2}" ;;
    --світ2-згори) exec godot --path "$proj" res://scenes/world2_view.tscn ;;
    --світ2-карта) exec godot --path "$proj" --script res://probes/world2_map.gd ;;
    --світ2-місця) exec godot --path "$proj" res://scenes/world2_spots.tscn ;;
    --демо-світ2) exec godot --path "$proj" "${vsync[@]}" -- --демо --світ2 ;;
    --демо) exec godot --path "$proj" "${vsync[@]}" -- --демо "${@:2}" ;;
    --демо-вікна) exec godot --path "$proj" "${vsync[@]}" -- --демо --вікна ;;
    --демо-крамар) exec godot --path "$proj" "${vsync[@]}" -- --демо --крамар "${@:2}" ;;
    --демо-персонаж) exec godot --path "$proj" -- --демо --персонаж Вовкодав ;;
    --парад) exec godot --path "$proj" --script res://probes/parade.gd ;;
    --рослини) exec godot --path "$proj" --script res://probes/plants.gd ;;
    --рухи-людини) exec godot --path "$proj" --script res://probes/human_moves.gd -- "${@:2}" ;;
    --рухи-монстрів) exec godot --path "$proj" --script res://probes/monster_moves.gd ;;
    --моделі) exec godot --path "$proj" "${vsync[@]}" res://scenes/model_viewer.tscn ;;
    --звірі-скан) exec godot --path "$proj" --script res://probes/scan_beasts.gd -- "${@:2}" ;;
    --нові-моделі) exec godot --path "$proj" --script res://probes/new_models.gd ;;
    # Сценою, а не --script: інакше немає автозавантажень, і проба тихо
    # вмирає на Net усередині hud.gd (полагоджено 05.09.2026).
    --святині) exec godot --path "$proj" res://scenes/shrines.tscn ;;
    --печери) exec godot --path "$proj" res://scenes/caves.tscn ;;
    --підземелля) exec godot --path "$proj" res://scenes/dungeons.tscn ;;
    --вітрина) exec godot --path "$proj" res://scenes/showcase.tscn ;;
    --демо-акаунт)   exec godot --path "$proj" -- --демо --акаунт конан --пароль таємниця --персонаж Вовкодав-2 ;;
    *)      exec godot --path "$proj" -e ;;
esac
