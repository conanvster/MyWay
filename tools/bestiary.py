def шлях_моделі(запис):
    """Людиноподібні й кістяки йдуть у `humanoids/` окремими .gltf зі
    спільними текстурами — так їх кладе сам конвеєр."""
    якщо = запис["конвеєр"] in ("Л", "К")
    if якщо:
        return ("res://models/own/humanoids/%s.gltf" % запис["назва"],
                os.path.join(MODELS, "humanoids",
                             запис["назва"] + ".gltf"))
    return ("res://models/own/%s.glb" % запис["назва"],
            os.path.join(MODELS, запис["назва"] + ".glb"))


def зробити_модель(запис):
    назва = запис["назва"]
    драйвер = os.path.join(ROOT, "tools", "blender", "from_catalog.py")
    вийшло = subprocess.run(
        ["blender", "--background", "--python", драйвер, "--", назва],
        capture_output=True, text=True, timeout=900)
    if вийшло.returncode != 0 or "[каталог]" not in вийшло.stdout:
        хвіст = (вийшло.stdout + "\n" + вийшло.stderr)[-400:]
        return "‼ збірка: %s" % хвіст.replace("\n", " ")[-200:]
    res, файл = шлях_моделі(запис)
    if запис["конвеєр"] not in ("Л", "К"):
        blend = os.path.join(BLEND, назва + ".blend")
        експорт = os.path.join(ROOT, "tools", "blender", "export_glb.py")
        друге = subprocess.run(
            ["blender", "--background", blend, "--python", експорт,
             "--", файл], capture_output=True, text=True, timeout=900)
        if друге.returncode != 0 or not os.path.exists(файл):
            return "‼ експорт: %s" % друге.stdout[-200:].replace("\n", " ")
    if not os.path.exists(файл):
        return "‼ файла немає: %s" % файл
    запис["модель"] = res
    return ""


def моделі(каталог, лише=None):
    треба = [x for x in каталог if x["конвеєр"] and not x["модель"]
             and (лише is None or x["де"] == лише)]
    print("[бестіарій] робити моделей: %d" % len(треба))
    зроблено, біда = 0, []
    for i, запис in enumerate(треба, 1):
        чому = зробити_модель(запис)
        if чому:
            біда.append((запис["назва"], чому))
            print("  %3d/%d ✗ %s — %s" % (i, len(треба), запис["назва"],
                                          чому))
        else:
            зроблено += 1
            print("  %3d/%d ✓ %s" % (i, len(треба), запис["назва"]))
        sys.stdout.flush()
        if i % 10 == 0:
            писати(каталог)
    писати(каталог)
    print("[бестіарій] зроблено %d, не вийшло %d" % (зроблено, len(біда)))
    for назва, чому in біда:
        print("   ‼ %s — %s" % (назва, чому))


