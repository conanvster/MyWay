    def зайнято(cx, cz, рад):
        for m in міста + села:
            r = m.get("рівне", m["радіус"]) + рад + 12.0
            if ((cx - m["центр"][0]) ** 2 + (cz - m["центр"][2]) ** 2
                    < r * r):
                return True
        for o in орієнтири:
            r = o["радіус"] + рад + 10.0
            if (cx - o["де"][0]) ** 2 + (cz - o["де"][2]) ** 2 < r * r:
                return True
        for z in зони:
            r = z["радіус"] + рад + 40.0
            if (cx - z["де"][0]) ** 2 + (cz - z["де"][2]) ** 2 < r * r:
                return True
