    # заглибині, інакше вона лежить плямою поверх схилу. Русло веде
    # ТУДИ Ж, куди й намальоване: клітини ті самі, з моделі.
    C_ = модель["клітина"]
    русла_гра = []
    for шлях in модель["русла"]:
        точки = []
        йде = None
        n_шлях = max(1, len(шлях) - 1)
        for k, (gx, gy) in enumerate(шлях):
            px, py = (gx + 0.5) * C_, (gy + 0.5) * C_
            x, z = у_гру(px, py)
            ix = min(n - 1, max(0, int(round(px / крок_px))))
            iy = min(n - 1, max(0, int(round(py / крок_px))))
            дно = метри[iy * n + ix]
            # Строго вниз: у полі рельєфу трапляються дрібні горби, і
            # без цього русло текло б угору, а вода стояла б сходинками.
            йде = дно if йде is None else min(йде, дно)
            частка = k / n_шлях
            шир = РІЧКА_ШИР_ВІД + (РІЧКА_ШИР_ДО - РІЧКА_ШИР_ВІД) * частка
            точки.append((x, z, йде, шир))
        русла_гра.append(точки)

    for точки in русла_гра:
        for x, z, дно, шир in точки:
            край = шир * РІЧКА_БЕРЕГ
            r = int(край / крок) + 1
            gx = int(round((x + ox) / крок_px))
            gy = int(round((z + oz) / крок_px))
            for dy in range(-r, r + 1):
                for dx in range(-r, r + 1):
                    jx, jy = gx + dx, gy + dy
                    if not (0 <= jx < n and 0 <= jy < n):
                        continue
                    d = math.hypot(dx, dy) * крок
                    if d > край:
                        continue
                    # Всередині русла — рівне дно, далі плавно вгору.
                    t = 0.0 if d <= шир * 0.5 else (d - шир * 0.5) / (край - шир * 0.5)
                    ціль = дно - РІЧКА_ГЛИБ * (1.0 - t * t)
                    i = jy * n + jx
                    if ціль < метри[i]:
                        метри[i] = ціль

