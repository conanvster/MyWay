def драбина():
    """Грейд за рівнем — з `game/data/items.json → грейди`. Своєї копії
    тут навмисно немає: драбину вже двічі міняли, і дві копії розійшлися
    б першою ж правкою."""
    речі = json.load(open(os.path.join(ROOT, "game", "data", "items.json"),
                          encoding="utf-8"))
    return речі["грейди"]["до рівня"]


def ключ(L):
    for грейд, верх in драбина().items():
        if L <= верх:
            return грейд
    return "SS"


def у_гру(каталог):
    """Дописати в `mobs.json` усіх, у кого є модель і кого там ще немає.

    Числа — за тією самою кривою рівня, що й усі види з 11-го:
    сила L+6, витривалість L+3, спритність 6+0,4L, повага 45…55·L^1,7,
    досвід 14…20·L, гроші 10…40·L. Не вигадую нової кривої на кожну
    партію — інакше баланс розповзеться сам собою.
    """
    import collections
    mobs = json.loads(open(MOBS, encoding="utf-8").read(),
                      object_pairs_hook=collections.OrderedDict)
    вже = {m["назва"] for k, m in mobs.items() if k != "_про"}
    номер = max(int(k) for k in mobs if k != "_про")
    додано = 0
    for x in sorted(каталог, key=lambda v: (v["рівень"], v["назва"])):
        if not x["модель"] or x["назва"] in вже:
            continue
        L = x["рівень"]
        підземелля = x["де"].startswith("підземелля")
        номер += 1
        mobs[str(номер)] = collections.OrderedDict([
            ("назва", x["назва"]), ("рівень", L),
            ("підземелля", True) if підземелля else ("рівень", L),
            ("стати", collections.OrderedDict([
                ("сила", L + 6), ("витривалість", L + 3),
                ("спритність", round(6 + 0.4 * L))])),
            ("помічає", 18.0), ("реакція_далеко", 2.0),
            ("реакція_близько", 0.2), ("повідець", 22.0),
            ("поклик", 12.0), ("блукання_радіус", 6.0),
            ("блукання_темп", 0.3), ("загроза_за_удар", 1.0),
            ("вигляд", collections.OrderedDict([
                ("модель", x["модель"]), ("колір", "#b09664"),
                ("зріст", x["вигляд"]["розмір"])])),
            ("повага", [round(45 * L ** 1.7), round(55 * L ** 1.7)]),
            ("досвід", [14 * L, 20 * L]),
            ("дроп", [
                collections.OrderedDict([("що", "гроші"), ("шанс", 0.95),
                                         ("від", 10 * L), ("до", 40 * L)]),
                collections.OrderedDict([("що", "шкура"), ("шанс", 0.4),
                                         ("від", 1), ("до", 1)]),
                collections.OrderedDict([("що", "зілля лікування"),
                                         ("шанс", 0.06), ("від", 1),
                                         ("до", 1)]),
                collections.OrderedDict([("що", "ключ святині " + ключ(L)),
                                         ("шанс", 0.25), ("від", 1),
                                         ("до", 1)]),
            ] + ([collections.OrderedDict([("що", "артефакт ока бога"),
                                           ("шанс", 0.02), ("від", 1),
                                           ("до", 1)])] if L >= 30 else [])),
            ("скіли", collections.OrderedDict([
                ("у відповідь", "поклик мертвих" if підземелля
                 else "вовчий-рик"),
                ("по кривднику", "темний-дотик" if підземелля
                 else "вовчий-укус")])),
        ])
        x["вид"] = номер
        додано += 1
    with open(MOBS, "w", encoding="utf-8") as f:
        json.dump(mobs, f, ensure_ascii=False, indent=2)
        f.write("\n")
    писати(каталог)
    print("[бестіарій] у mobs.json додано %d, усього видів %d"
          % (додано, len(mobs) - 1))


def головне():
    р = argparse.ArgumentParser(add_help=False)
    р.add_argument("--опис", action="store_true")
    р.add_argument("--перезібрати", action="store_true")
    р.add_argument("--список", action="store_true")
    р.add_argument("--моделі", action="store_true")
    р.add_argument("--де", default=None)
    р.add_argument("--у-гру", action="store_true", dest="у_гру")
    а = р.parse_args()
    if а.перезібрати:
        писати(зібрати())
    каталог = читати()
    if а.моделі:
        моделі(каталог, а.де)
        документ(каталог)
        return
    if а.у_гру:
        у_гру(каталог)
        документ(каталог)
        return
    if а.опис:
        документ(каталог)
        return
    групи = {}
    for x in каталог:
        групи.setdefault(x["де"], []).append(x)
    for де in sorted(групи):
        свої = групи[де]
        рівні = [x["рівень"] for x in свої]
        print("  %-14s видів %3d, рівні %2d…%2d, моделей %d"
              % (де, len(свої), min(рівні), max(рівні),
                 len([x for x in свої if x["модель"]])))
    print("  разом %d видів, моделей %d"
          % (len(каталог), len([x for x in каталог if x["модель"]])))


if __name__ == "__main__":
    головне()
