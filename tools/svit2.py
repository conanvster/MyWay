def пости_вартових(карта):
    """Пост вартового там, де вартового-мешканця немає. Повертає, скільки
    поставлено."""
    поставлено = 0
    for місце in карта.get("міста", []) + карта.get("села", []):
        if any(m.get("ремесло") == "вартовий"
               for m in місце.get("мешканці", [])):
            місце.pop("вартові", None)
            continue
        x, _, z = місце["центр"]
        # Ближче до краю двору, ніж коло мешканців (0,34 радіуса), —
        # щоб не стати нікому на голову.
        r = float(місце["радіус"]) * 0.55
        місце["вартові"] = [{"хто": "Вартовий",
                             "де": [round(x + r, 1), 0, round(z, 1)]}]
        поставлено += 1
    карта["охорона поселень"] = ОХОРОНА_ПОСЕЛЕНЬ
    return поставлено


def найближчі(мешканці):
    близько = None
    for i in range(len(мешканці)):
        for j in range(i + 1, len(мешканці)):
            a, b = мешканці[i]["де"], мешканці[j]["де"]
            d = math.dist((a[0], a[2]), (b[0], b[2]))
            if близько is None or d < близько[0]:
                близько = (d, мешканці[i]["хто"], мешканці[j]["хто"])
    return близько


def розвести_мешканців():
    """Поставити мешканців кожного міста рівно по колу — і нікого в
    нікому."""
    шлях = os.path.join(ДАНІ, "map2.json")
    карта = json.load(open(шлях, encoding="utf-8"))
    вад = 0
    for місто in карта.get("міста", []) + карта.get("села", []):
        люди = місто.get("мешканці", [])
        if len(люди) < 2:
            continue
        було = найближчі(люди)
        x, _, z = місто["центр"]
        r = float(місто["радіус"]) * 0.34
        for k, житель in enumerate(люди):
            a = 6.2832 * (k + 0.5) / len(люди)
            житель["де"] = [round(x + math.cos(a) * r, 1), 0,
                            round(z + math.sin(a) * r, 1)]
        стало = найближчі(люди)
        мітка = "‼" if стало[0] < ПРОСВІТ_МІЖ_NPC else " "
        if стало[0] < ПРОСВІТ_МІЖ_NPC:
            вад += 1
        print("  %s %-15s мешканців %d · було %.1f м (%s і %s) → стало "
              "%.1f м" % (мітка, місто["назва"], len(люди), було[0],
                          було[1], було[2], стало[0]))
    with open(шлях, "w", encoding="utf-8") as f:
        json.dump(карта, f, ensure_ascii=False, indent=1)
    print("[мешканці] переставлено; тісніших за %.0f м: %d"
          % (ПРОСВІТ_МІЖ_NPC, вад))
    return вад


