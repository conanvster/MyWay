def смуга_в(задум, зона, точка):
    """Рівні в цій точці зони: проєкція на ламану опор, лінійно між
    сусідніми опорами, за краями — межі крайньої опори."""
    ланка = [o for o in задум["опори"] if o["зона"] == зона]
    if not ланка:
        return None
    if len(ланка) == 1:
        return (float(ланка[0]["від"]), float(ланка[0]["до"]))
    точки = [o["де"] for o in ланка]
    краще, s_краще, пройдено = None, 0.0, 0.0
    for i in range(len(точки) - 1):
        a, b = точки[i], точки[i + 1]
        vx, vz = b[0] - a[0], b[1] - a[1]
        довжина = math.hypot(vx, vz) or 1.0
        t = ((точка[0] - a[0]) * vx + (точка[1] - a[1]) * vz) / довжина ** 2
        t = min(1.0, max(0.0, t))
        px, pz = a[0] + vx * t, a[1] + vz * t
        d = math.hypot(точка[0] - px, точка[1] - pz)
        if краще is None or d < краще:
            краще, s_краще = d, пройдено + t * довжина
        пройдено += довжина
    пройдено = 0.0
    for i in range(len(точки) - 1):
        довжина = math.hypot(точки[i + 1][0] - точки[i][0],
                             точки[i + 1][1] - точки[i][1]) or 1.0
        if s_краще <= пройдено + довжина or i == len(точки) - 2:
            t = min(1.0, max(0.0, (s_краще - пройдено) / довжина))
            a, b = ланка[i], ланка[i + 1]
            return (a["від"] + (b["від"] - a["від"]) * t,
                    a["до"] + (b["до"] - a["до"]) * t)
        пройдено += довжина
    return (float(ланка[-1]["від"]), float(ланка[-1]["до"]))


