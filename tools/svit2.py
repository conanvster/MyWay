def _у_многокутнику(p, кути):
    x, z = p
    всередині = False
    for i in range(len(кути)):
        (x1, z1), (x2, z2) = кути[i], кути[(i + 1) % len(кути)]
        if (z1 > z) != (z2 > z) and \
                x < (x2 - x1) * (z - z1) / (z2 - z1) + x1:
            всередині = not всередині
    return всередині


def _до_відрізка(p, a, b):
    ax, az = a
    bx, bz = b
    dx, dz = bx - ax, bz - az
    t = ((p[0] - ax) * dx + (p[1] - az) * dz) / max(1e-9, dx * dx + dz * dz)
    t = min(1.0, max(0.0, t))
    return math.hypot(p[0] - ax - dx * t, p[1] - az - dz * t)


def _кути_дому(де, кут, w, d):
    """Чотири кути прямокутника w×d (метри), повернутого на `кут`."""
    c, s = math.cos(кут), math.sin(кут)
    out = []
    for sx, sz in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
        lx, lz = sx * w / 2, sz * d / 2
        # Поворот Godot навколо Y: локальне x → (cos, -sin), z → (sin, cos).
        out.append((де[0] + lx * c + lz * s, де[1] - lx * s + lz * c))
    return out


def _перетин(a, b):
    """Чи перетинаються два опуклі чотирикутники (теорема про вісь)."""
    for многокутник in (a, b):
        for i in range(len(многокутник)):
            x1, z1 = многокутник[i]
            x2, z2 = многокутник[(i + 1) % len(многокутник)]
            nx, nz = z2 - z1, x1 - x2
            pa = [nx * x + nz * z for x, z in a]
            pb = [nx * x + nz * z for x, z in b]
            if max(pa) < min(pb) or max(pb) < min(pa):
                return False
    return True


def _поворот_до(від, до):
    """Градуси повороту, за якого перед дому (локальне +z) дивиться
    з `від` на `до`."""
