def головна():
    d = зібрати()
    текст = звіт(d) + "\n" + задачі(d) + "\n"
    with open(ВИХІД, "w", encoding="utf-8") as f:
        f.write(текст)
    треба = sum(d["треба_в"].values())
    print("[спорядження] комірок %d, повний набір %d баз на грейд, "
          "грейдів %d" % (len(d["слоти"]), len(d["слоти"]),
                          len(d["смуги"])))
    print("              обов'язкових місць %d, закрито %d, бракує %d; "
          "речей усього %d"
          % (треба, sum(d["покрито_в"].values()),
             треба - sum(d["покрито_в"].values()), len(d["носиме"])))
    без = [н for н in d["носиме"] if not d["падає"].get(н)]
    print("              не падає нізвідки: %d" % len(без))
    print("              → %s" % os.path.relpath(ВИХІД, ROOT))




