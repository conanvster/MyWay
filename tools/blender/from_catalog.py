"""Модель із каталогу: `spec/бестіарій.json` → .blend через свій конвеєр.

Слово замовника 20.09.2026: «згенеруй 3d моделі — згодом покращімо їх
візуалізацію, а зараз потрібно розуміти чи достатньо їх на мапі». Тому
тут не ручна робота над кожним видом, а переклад двох полів каталогу
(розмір і риси) у набір чисел того конвеєра, якому вид належить.

Риси беруться зі слів опису (`tools/bestiary.py → риси_з_опису`), тож
«роги» в описі справді дають роги, «кристал» — кристали, «кістки» —
кістяне тіло. Це навмисно грубо: доводити вигляд кожного виду окремо —
робота на потім, і рядок у каталозі для цього вже є.

Запуск (сам не кличеться — його кличе `tools/bestiary.py --моделі`):
    blender --background --python tools/blender/from_catalog.py -- \\
        "<назва виду>" [тека_для_картинок]
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CATALOG = os.path.join(ROOT, "spec", "бестіарій.json")


def знайти(назва):
    for x in json.load(open(CATALOG, encoding="utf-8")):
        if x["назва"] == назва:
            return x
    sys.exit("‼ у каталозі немає виду: %s" % назва)


# ─────────────────── переклад рис у числа конвеєрів ─────────────────

def чотирилапий(запис):
    """Ч — `beasts.py`. Пропорції від розміру, решта від рис."""
    в = запис["вигляд"]
    риси = в["риси"]
    L = max(0.35, в["розмір"])
    H = L * (0.85 if "велет" in риси else 0.70)
    s = dict(L=round(L, 2), H=round(H, 2), W=round(L * 0.21, 2),
             head=round(L * 0.14, 2), snout=round(L * 0.16, 2),
             ears=("гострі", round(L * 0.10, 2)),
             tail=("пухнастий", round(L * 0.45, 2)),
             fur=в["текстура"], belly="хутро-світле",
             attack="укус", eyes=tuple(в["колір"]))
    if "роги" in риси:
        s["antlers"] = round(L * 0.5, 2)
    if "шипи" in риси or "кристали" in риси:
        s["spikes"] = 7
    if "броня" in риси or "кістки" in риси:
        s["plates"] = True
    if "велет" in риси:
        s["hump"] = round(L * 0.18, 2)
        s["attack"] = "лапа"
    if "лід" in риси:
        s["fur"] = "хутро-світле"
        s["belly"] = "хутро-світле"
    if "вогонь" in риси:
        s["fur"] = "хутро-руде"
    return "beasts", s


def людиноподібний(запис, кістяк=False):
    """Л і К — `humanoids.py`. Кістяк — тіло з кісток, решта — шкіра
    потрібної барви з дрібницями."""
    в = запис["вигляд"]
    риси = в["риси"]
    if кістяк or "кістки" in риси and запис["конвеєр"] == "К":
        s = dict(bones=True, moves="мрець", eyes=(0.4, 0.8, 1.0))
        if "броня" in риси:
            s["outfit"] = [("шолом-кістяка", (0.45, 0.45, 0.48))]
            s["weapon"] = "меч"
            s["moves"] = "зброя"
        return "humanoids", s
    колір = tuple(в["колір"])
    s = dict(skin=("хутро", в["текстура"]), moves="звір",
             eyes=колір if колір else (0.9, 0.7, 0.2))
    if "велет" in риси:
        s["bulk"] = 0.05
    if "роги" in риси:
        s["horns"] = 0.3
    if "крила" in риси:
        s["wings"] = 1.4
    if "кристали" in риси or "броня" in риси:
        s["outfit"] = [("кіраса", (0.42, 0.42, 0.5)),
                       ("наплічники", (0.36, 0.36, 0.44))]
        s["moves"] = "зброя"
        s["weapon"] = "меч"
    elif "кістки" in риси:
        s["skin"] = ("колір", "зомбі")
        s["outfit"] = [("лахміття", (0.3, 0.3, 0.26))]
    if "тінь" in риси:
        s["skin"] = ("колір", "наг")
    if "отрута" in риси:
        s["fangs"] = True
    if "зайві руки" in риси:
        s["claws"] = True
    return "humanoids", s


def змія(запис):
    в = запис["вигляд"]
    риси = в["риси"]
    L = max(1.2, в["розмір"] * 4.0)
    s = dict(length=round(L, 2), r=round(L * 0.035, 3), segs=12,
             skin=в["текстура"] if "луска" in в["текстура"]
             else "луска-темна",
             belly=(0.7, 0.66, 0.5), eyes=tuple(в["колір"]))
    if "роги" in риси or "кристали" in риси:
        s["crest"] = True
    if "велет" in риси:
        s["legs"] = True
    if "вогонь" in риси or "тінь" in риси:
        s["glow"] = True
    return "serpents", s


def членистоногий(запис):
    в = запис["вигляд"]
    риси = в["риси"]
    L = max(0.3, в["розмір"])
    s = dict(L=round(L, 2), shell=tuple(в["колір"]), claws=1.1,
             eyes=(1.0, 0.3, 0.05))
    if "броня" in риси or "кристали" in риси:
        s["plates"] = True
    if "вогонь" in риси or "тінь" in риси or "кристали" in риси:
        s["glow"] = True
    return "scorpions", s


def крилатий(запис):
    в = запис["вигляд"]
    риси = в["риси"]
    L = max(0.4, в["розмір"])
    s = dict(L=round(L, 2), лап=2, шия=0.2, розмах=round(L * 3.0, 2),
             голова="птах" if "птах" in запис["опис"] else "кажан",
             шкіра=tuple(в["колір"]),
             перетинка=tuple(min(1.0, c + 0.12) for c in в["колір"]),
             очі=(1.0, 0.6, 0.1), хвіст=round(L * 0.7, 2))
    if "велет" in риси:
        s["лап"] = 4
        s["шия"] = 0.5
        s["голова"] = "дракон"
    if "роги" in риси:
        s["роги"] = 0.22
    if "шипи" in риси or "кристали" in риси:
        s["шипи"] = True
    if "кістки" in риси:
        s["кістяк"] = True
    if "тінь" in риси or "вогонь" in риси:
        s["світяться"] = True
    return "winged", s


def числа(запис):
    к = запис["конвеєр"]
    if к == "Ч":
        return чотирилапий(запис)
    if к == "Л":
        return людиноподібний(запис)
    if к == "К":
        return людиноподібний(запис, кістяк=True)
    if к == "З":
        return змія(запис)
    if к == "С":
        return членистоногий(запис)
    if к == "Д":
        return крилатий(запис)
    sys.exit("‼ невідомий конвеєр: %s" % к)


def main():
    args = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    if not args:
        sys.exit("‼ дай назву виду")
    назва = args[0]
    shots = args[1] if len(args) > 1 else None
    запис = знайти(назва)
    модуль, s = числа(запис)
    mod = __import__(модуль)
    mod.SPECIES[назва] = s
    # `beasts.py` бере шлях до .blend другим доводом, решта — самі
    # кладуть у art/monsters.
    if модуль == "beasts":
        out = os.path.join(ROOT, "art", "monsters", назва + ".blend")
        mod.build(назва, out, shots)
    else:
        mod.build(назва, shots)
    print("[каталог] %s · конвеєр %s" % (назва, запис["конвеєр"]))


if __name__ == "__main__":
    main()
